from __future__ import annotations

from abc import ABC, abstractmethod

class SyncBackend(ABC):
    @property
    @abstractmethod
    def kind(self) -> str: ...

    @property
    @abstractmethod
    def remove_action(self) -> str: ...

    @property
    @abstractmethod
    def remove_description(self) -> str: ...

    @property
    @abstractmethod
    def scanner(self): ...

    @abstractmethod
    def refresh(self, folder): ...

    @abstractmethod
    def clear_memory_cache(self, root=None): ...

    @abstractmethod
    def folder_hash(self, folder): ...

    @abstractmethod
    def folder_ref(self, node): ...

    @abstractmethod
    def create_folder(self, parent, name): ...

    @abstractmethod
    def rename(self, item, name): ...

    @abstractmethod
    def remove(self, item): ...

    @abstractmethod
    def schedule_export(self, job, transfers): ...

    @abstractmethod
    def schedule_import(self, job, parent, name: str, transfers): ...

    @abstractmethod
    def staging_requirement(self, node, workspace, include_output=True): ...

    @abstractmethod
    def download_target(self, parent, name): ...

    @abstractmethod
    def overlaps(self, root, other, other_root): ...

    @abstractmethod
    def contains_staging(self, root, staging): ...

    @abstractmethod
    def discard_staged(self, node, workspace): ...

    @abstractmethod
    def root_label(self, root) -> str: ...

    @abstractmethod
    def node_label(self, node) -> str: ...

    @abstractmethod
    def child_root(self, node, opposite_node, parent_node): ...

    @abstractmethod
    def can_create_folder(self, parent_node) -> bool: ...

    @abstractmethod
    def open_file(self, node) -> None: ...

    @abstractmethod
    def folder_size(self, node) -> int: ...

    @abstractmethod
    def password_item(self, node): ...

    @abstractmethod
    def root_password_item(self, root): ...

    @abstractmethod
    def password_prompt_item(self, error, items): ...

    @abstractmethod
    def set_password(self, item, password: str) -> None: ...

    @abstractmethod
    def owns_item(self, item) -> bool: ...

    @abstractmethod
    def matches_error(self, error) -> bool: ...
